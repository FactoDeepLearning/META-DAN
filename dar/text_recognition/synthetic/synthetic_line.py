from dar.generic.utils import randint, rand_uniform, resize_max
import numpy as np
from PIL import ImageFont, ImageDraw, Image


DEFAULT_SYN_CONFIG = {
        "background_color_default": (255, 255, 255),
        "text_color_default": (0, 0, 0),
        "font_size_min": 35,
        "font_size_max": 45,
        "color_mode": "RGB",
        "padding_left_ratio_min": 0.00,
        "padding_left_ratio_max": 0.05,
        "padding_right_ratio_min": 0.02,
        "padding_right_ratio_max": 0.2,
        "padding_top_ratio_min": 0.02,
        "padding_top_ratio_max": 0.1,
        "padding_bottom_ratio_min": 0.02,
        "padding_bottom_ratio_max": 0.1,
    }


def generate_random_text_line_label(charset: list[str], min_chars: int, max_chars: int) -> str:
    """
    Generate a random string label by randomly picking characters from the charset.
    The length of the generated string follow a uniform distribution between min_chars and max_chars.
    """
    num_chars = randint(min_chars, max_chars)
    words = list()
    while num_chars >= 1:
        word_len = randint(1, min(num_chars, 8)+1)
        num_chars -= (word_len + 1)
        words.append("".join([charset[randint(0, len(charset))] for _ in range(word_len)]))
    return " ".join(words)


def generate_typed_text_line_image_default_config(text: str, font_path: str, max_width: int=None, font_size: int=None) -> np.ndarray:
    return generate_typed_text_line_image_from_params(text, DEFAULT_SYN_CONFIG, font_path, max_width=max_width, font_size=font_size)


def generate_typed_text_line_image_from_params(text: str, 
                                               syn_config: dict, 
                                               font_path: str, 
                                               bg_color: tuple[int, int, int]=(255, 255, 255), 
                                               txt_color: tuple[int, int, int]=(0, 0, 0), 
                                               max_width: int|None=None, 
                                               font_size: int|None=None) -> np.ndarray:
    assert len(text) > 0
    text = handle_text_exceptions(text)

    if "text_color_default" in syn_config:
        txt_color = syn_config["text_color_default"]
    if "background_color_default" in syn_config:
        bg_color = syn_config["background_color_default"]

    if font_size is None:
        text_width = max_width
        i = 0
        while i < 20 and (text_width is None or (max_width and text_width >= max_width) or text_width == 0 or text_height == 0):
            i += 1
            font_size = randint(syn_config["font_size_min"], syn_config["font_size_max"]+1)
            fnt = ImageFont.truetype(font_path, font_size)
            text_width, text_height = get_image_size(fnt, text)
        if i >= 20:
            fnt = ImageFont.truetype(font_path, syn_config["font_size_min"])
    else:
        fnt = ImageFont.truetype(font_path, font_size)
        text_width, text_height = get_image_size(fnt, text)

    padding_top = int(rand_uniform(syn_config["padding_top_ratio_min"], syn_config["padding_top_ratio_max"])*text_height)
    padding_bottom = int(rand_uniform(syn_config["padding_bottom_ratio_min"], syn_config["padding_bottom_ratio_max"])*text_height)
    padding_left = int(rand_uniform(syn_config["padding_left_ratio_min"], syn_config["padding_left_ratio_max"])*text_width)
    padding_right = int(rand_uniform(syn_config["padding_right_ratio_min"], syn_config["padding_right_ratio_max"])*text_width)
    padding = [padding_top, padding_bottom, padding_left, padding_right]
    img = generate_typed_text_line_image(text, fnt, bg_color, txt_color, syn_config["color_mode"], padding)

    if max_width and img.shape[1] > max_width:
        img = resize_max(img, max_width)
    return img


def generate_typed_text_line_image(text: str, 
                                   font: ImageFont, 
                                   bg_color: tuple[int, int, int], 
                                   txt_color: tuple[int, int, int], 
                                   color_mode: str, 
                                   padding: tuple[int, int, int, int]) -> np.ndarray:
    padding_top, padding_bottom, padding_left, padding_right = padding
    text_width, text_height = get_image_size(font, text)
    img_height = padding_top + padding_bottom + text_height
    img_width = padding_left + padding_right + text_width
    img = Image.new(color_mode, (img_width, img_height), color=bg_color)
    d = ImageDraw.Draw(img)
    d.text((padding_left, padding_bottom), text, font=font, fill=txt_color, spacing=0)
    return np.array(img)


def handle_text_exceptions(text: str) -> str:
    return text.replace('ﭐ', "ا")


def get_image_size(font: ImageFont, text: str) -> tuple[int, int]:
    """
    Return the size of the image that would be generated by fiven font and text string as (width, height)
    """
    try:
        return font.getsize(text)
    except OSError:
        print(f"Error getting size of font '{font.path}' (size: {font.size}) for text: '{text}'", flush=True)
        return font.getsize(text)